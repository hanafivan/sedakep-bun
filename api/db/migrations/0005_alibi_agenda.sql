-- Alibi (dengan approval 3 tingkat) dan agenda.
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS alibi_requests (
  id              INT UNSIGNED NOT NULL AUTO_INCREMENT,
  legacy_id       VARCHAR(64) DEFAULT NULL,
  user_id         INT UNSIGNED NOT NULL,
  name            VARCHAR(120) NOT NULL,
  nip             VARCHAR(18) DEFAULT NULL,
  grade           VARCHAR(20) DEFAULT NULL,
  position        VARCHAR(150) DEFAULT NULL,
  organization_name VARCHAR(150) DEFAULT NULL,
  day_count       VARCHAR(20) DEFAULT NULL,
  alibi_date      DATE DEFAULT NULL,
  alibi_type      VARCHAR(50) DEFAULT NULL,
  reason          TEXT DEFAULT NULL,
  time_start      VARCHAR(10) DEFAULT NULL,
  time_end        VARCHAR(10) DEFAULT NULL,
  approver_1_name VARCHAR(150) DEFAULT NULL,
  approver_1_nip  VARCHAR(18) DEFAULT NULL,
  approver_1_position VARCHAR(150) DEFAULT NULL,
  approver_2_name VARCHAR(150) DEFAULT NULL,
  approver_2_nip  VARCHAR(18) DEFAULT NULL,
  approver_2_position VARCHAR(150) DEFAULT NULL,
  status          ENUM('submitted','in_review','approved','rejected','cancelled') NOT NULL DEFAULT 'submitted',
  admin_decision  ENUM('pending','accepted','rejected','cancelled') NOT NULL DEFAULT 'pending',
  approver_1_status ENUM('pending','accepted','rejected') NOT NULL DEFAULT 'pending',
  approver_2_status ENUM('pending','accepted','rejected') NOT NULL DEFAULT 'pending',
  admin_decided_at TIMESTAMP NULL DEFAULT NULL,
  approver_1_decided_at TIMESTAMP NULL DEFAULT NULL,
  approver_2_decided_at TIMESTAMP NULL DEFAULT NULL,
  verdict_note    TEXT DEFAULT NULL,
  printed_at      DATE DEFAULT NULL,
  created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_alibi_requests_legacy (legacy_id),
  KEY idx_alibi_user_date (user_id, alibi_date),
  KEY idx_alibi_status (status),
  CONSTRAINT fk_alibi_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS agendas (
  id         INT UNSIGNED NOT NULL AUTO_INCREMENT,
  legacy_id  VARCHAR(64) DEFAULT NULL,
  user_id    INT UNSIGNED NOT NULL,
  name       VARCHAR(120) DEFAULT NULL,
  nip        VARCHAR(18)  DEFAULT NULL,
  title      VARCHAR(255) NOT NULL,
  place      VARCHAR(200) DEFAULT NULL,
  start_at   DATETIME     DEFAULT NULL,
  end_at     DATETIME     DEFAULT NULL,
  report     TEXT         DEFAULT NULL,
  reported_at TIMESTAMP   NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_agendas_legacy (legacy_id),
  KEY idx_agendas_user (user_id),
  KEY idx_agendas_start (start_at),
  CONSTRAINT fk_agendas_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
